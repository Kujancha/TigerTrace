"""Manifest validation and reproducible balanced batches; no test images read in training."""

import csv
import hashlib
import json
import random
from collections import Counter, defaultdict
from pathlib import Path
from PIL import Image, ImageOps


def sha256(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def save_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".tmp")
    temp.write_text(json.dumps(value, indent=2, allow_nan=False), encoding="utf-8")
    temp.replace(path)


def save_csv(path, rows):
    if not rows:
        return
    with Path(path).open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def load_manifest(path, prepared=None):
    path = Path(path)
    m = json.loads(path.read_text(encoding="utf-8"))
    if m.get("schema_version") != 1 or "prepared_root" not in m:
        raise ValueError("Expected a manifest generated by the split command.")
    root = Path(prepared or m["prepared_root"]).resolve()
    partitions = m["identity_splits"]
    if set(partitions) != {"train", "val", "test"}:
        raise ValueError("Manifest needs train/val/test identity groups.")
    membership = {}
    for split, ids in partitions.items():
        for identity in ids:
            if identity in membership:
                raise ValueError("Identity occurs in multiple partitions.")
            membership[identity] = split
    seen = set()
    pixels = set()
    role_counts = defaultdict(Counter)
    for row in m["records"]:
        if membership.get(row["identity"]) != row["split"]:
            raise ValueError("Image partition disagrees with identity partition.")
        allowed = {"train"} if row["split"] == "train" else {"gallery", "query"}
        if row["role"] not in allowed:
            raise ValueError("Invalid image role.")
        if row["path"] in seen or row["decoded_sha256"] in pixels:
            raise ValueError("Duplicate image path or decoded hash in manifest.")
        seen.add(row["path"])
        pixels.add(row["decoded_sha256"])
        resolved = (root / row["path"]).resolve()
        if root not in resolved.parents:
            raise ValueError("Image path escapes prepared root.")
        role_counts[row["identity"]][row["role"]] += 1
    for identity, split in membership.items():
        c = role_counts[identity]
        if split == "train" and c["train"] < 2:
            raise ValueError("Training identity needs >=2 images.")
        if split != "train" and (not c["gallery"] or not c["query"]):
            raise ValueError("Evaluation identity needs gallery and query.")
    return m, root, sha256(path)


def verify_train_val(manifest, root, progress=lambda x: x):
    # Only train/validation image bytes are read; no final-test inspection by training.
    for row in progress(
        [r for r in manifest["records"] if r["split"] in {"train", "val"}]
    ):
        p = root / row["path"]
        if sha256(p) != row["sha256"]:
            raise ValueError("Image changed since splitting: " + row["path"])
        with Image.open(p) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
            im.load()
            digest = hashlib.sha256(str(im.size).encode() + im.tobytes()).hexdigest()
        if digest != row["decoded_sha256"]:
            raise ValueError("Decoded image differs: " + row["path"])


class BalancedBatches:
    def __init__(self, labels, p, k, steps, seed):
        self.by_id = defaultdict(list)
        for j, label in enumerate(labels):
            self.by_id[label].append(j)
        if p < 2 or k < 2 or steps < 1 or len(self.by_id) < p:
            raise ValueError(
                "Need P>=2 identities, K>=2 images, steps>=1, and at least P training identities."
            )
        if any(len(v) < k for v in self.by_id.values()):
            raise ValueError(
                "Each training identity needs K distinct images. Reduce K."
            )
        self.p, self.k, self.steps, self.seed, self.epoch = p, k, steps, seed, 0

    def __len__(self):
        return self.steps

    def __iter__(self):
        rng = random.Random(self.seed + self.epoch * 1000003)
        for _ in range(self.steps):
            yield [
                j
                for label in rng.sample(sorted(self.by_id), self.p)
                for j in rng.sample(self.by_id[label], self.k)
            ]
